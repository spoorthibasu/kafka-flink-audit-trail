#!/usr/bin/env python3
"""Where each engine's official documentation defines LAST_VALUE with IGNORE NULLS.

Every entry below was copied from the page at the URL, fetched in a browser on the
date shown; the "line" is the page text verbatim (a trailing permalink "#" that Trino's
pages render after each signature is dropped). Writes engine_docs.csv and the
"Engine documentation" section of SUMMARY.md.

  python3 bench/engine_docs.py --out results
"""
import argparse
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from benchmark import md_table  # noqa: E402
from summary_sections import replace_section  # noqa: E402

SECTION_HEADING = "## Engine documentation for LAST_VALUE with IGNORE NULLS"
FETCHED = "2026-10-20"

DOCS = [
    {"engine": "DuckDB",
     "url": "https://duckdb.org/docs/lts/sql/functions/window_functions",
     "version": "DuckDB 1.4 (LTS); the page reads \"This page is for DuckDB 1.4 (LTS).\"",
     "line": "last_value(expr[ ORDER BY ordering][ IGNORE NULLS])",
     "placement": "inside the parentheses",
     "note": "Description on the page: \"Returns expr evaluated at the row that is the last row (among rows with a "
             "non-null value of expr if IGNORE NULLS is set) of the window frame.\""},
    {"engine": "Spark SQL",
     "url": "https://spark.apache.org/docs/latest/sql-ref-syntax-qry-select-window.html",
     "version": "Spark 4.2.0; the page title reads \"Window Functions - Spark 4.2.0 Documentation\"",
     "line": "window_function [ nulls_option ] OVER",
     "placement": "after the closing parenthesis, before OVER",
     "note": "The page also shows \"Note: Only LAG | LEAD | NTH_VALUE | FIRST_VALUE | LAST_VALUE can be used with "
             "IGNORE NULLS.\" and the example line \"LAST_VALUE(v) IGNORE NULLS OVER w last_value\"."},
    {"engine": "Trino",
     "url": "https://trino.io/docs/current/functions/window.html",
     "version": "Trino 484; the page title ends \"Trino 484 Documentation\"",
     "line": "last_value(x) → [same as input]",
     "placement": "not shown on the page",
     "note": "The Value functions section states: \"By default, null values are respected. If IGNORE NULLS is "
             "specified, all rows where x is null are excluded from the calculation.\" Neither this page nor "
             "https://trino.io/docs/current/sql/select.html shows where IGNORE NULLS is written; CI runs the "
             "after-the-parenthesis form on Trino 483."},
    {"engine": "Athena",
     "url": "https://docs.aws.amazon.com/athena/latest/ug/engine-versions-reference-0003.html",
     "version": "Athena engine version 3",
     "line": "Cause: IGNORE NULLS can now be used only with the value functions first_value, last_value, nth_value, "
             "lead, and lag. This change was made to conform to the ANSI SQL specification.",
     "placement": "not shown on the page",
     "note": "No Athena page found that gives a LAST_VALUE syntax line. This page links \"value functions\" to "
             "https://trino.io/docs/current/functions/window.html#value-functions, the Trino 484 page above, and "
             "does not state which Trino version engine version 3 follows."},
]


def section():
    lines = [SECTION_HEADING, "",
             "Official pages that define LAST_VALUE with IGNORE NULLS, fetched on %s. The syntax line is copied "
             "verbatim from each page. Generated by `bench/engine_docs.py`." % FETCHED, ""]
    lines.append(md_table(["Engine", "Page", "Documented version", "Syntax line on the page", "IGNORE NULLS placement"],
                          [[d["engine"], d["url"], d["version"], "`%s`" % d["line"] if d["engine"] != "Athena" else d["line"],
                            d["placement"]] for d in DOCS]))
    lines.append("")
    for d in DOCS:
        lines.append("- %s: %s" % (d["engine"], d["note"]))
    lines.append("")
    lines.append("CI (`ci/run_sql_matrix.py`) checks the placements on DuckDB 1.4.5, Spark 4.0.4 and Trino 483, which "
                 "are the versions it runs, not the documentation versions above.")
    lines.append("")
    lines.append("Files: `engine_docs.csv`.")
    lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results")
    args = ap.parse_args()
    with open(os.path.join(args.out, "engine_docs.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["engine", "url", "version", "line", "placement", "note", "fetched"])
        w.writeheader()
        for d in DOCS:
            w.writerow(dict(d, fetched=FETCHED))
    replace_section(os.path.join(args.out, "SUMMARY.md"), SECTION_HEADING, section())
    print("engine_docs.csv written; SUMMARY.md section written")


if __name__ == "__main__":
    main()
